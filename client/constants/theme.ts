export function applyThemeSkin(
  baseTheme: ThemeColors,
  skinId: ThemeSkinId,
  isDark: boolean,
): ThemeColors {
  const overrides = SKIN_OVERRIDES[skinId];
  if (!overrides) return baseTheme;
  const modeOverrides = isDark ? overrides.dark : overrides.light;
  const merged = { ...baseTheme, ...modeOverrides };
  return {
    ...merged,
    atmosphereTop:
      modeOverrides.atmosphereTop ??
      (isDark ? merged.backgroundRoot : merged.gradientLightBg2),
    atmosphereMid: modeOverrides.atmosphereMid ?? merged.backgroundDefault,
    atmosphereBottom:
      modeOverrides.atmosphereBottom ??
      (isDark ? merged.backgroundRoot : merged.gradientLightBg),
    patternColor: modeOverrides.patternColor ?? merged.secondary,
    glowPrimary: modeOverrides.glowPrimary ?? `${merged.primary}26`,
    glowScholar: modeOverrides.glowScholar ?? `${merged.scholar}22`,
    surfaceStroke: modeOverrides.surfaceStroke ?? merged.primaryBorder,
    primarySoft: modeOverrides.primarySoft ?? merged.primarySubtle,
    premiumHighlight: modeOverrides.premiumHighlight ?? merged.gradientEnd,
  };
}

