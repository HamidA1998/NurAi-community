export function getThemedCategoryColors(theme: any, skinId: ThemeSkinId) {
  if (skinId === "default") return CategoryColors;
  const overrides = SKIN_OVERRIDES[skinId];
  if (!overrides) return CategoryColors;
  return {
    ...CategoryColors,
    emerald: {
      bg: overrides.light.gradientLightBg,
      text: overrides.light.primary,
      dark: { bg: overrides.dark.gradientStart, text: overrides.dark.primary },
    },
  };
}

