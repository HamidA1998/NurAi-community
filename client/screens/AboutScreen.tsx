function InfoCard({
  icon,
  title,
  description,
  theme,
  index,
}: {
  icon: AppIconName;
  title: string;
  description: string;
  theme: any;
  index: number;
}) {
  return (
    <Animated.View
      entering={FadeInDown.delay(index * 80).duration(300)}
      style={[styles.infoCard, { backgroundColor: theme.cardBackground }]}
    >
      <GeometricCardPattern color={theme.primary} opacity={0.012} />
      <View
        style={[styles.infoIcon, { backgroundColor: `${theme.primary}18` }]}
      >
        <AppIcon name={icon} size={20} color={theme.primary} />
      </View>
      <View style={styles.infoContent}>
        <ThemedText style={styles.infoTitle}>{title}</ThemedText>
        <ThemedText type="small" style={{ color: theme.textSecondary }}>
          {description}
        </ThemedText>
      </View>
    </Animated.View>
  );
}

